func Threshold(code string) int64 {
	for _, j := range Jurisdictions {
		if j.Code == code {
			return j.Threshold
		}
	}
	return 0
}
func NeedsRegistration(code string, total int64) bool {
	limit := Threshold(code)
	if limit == 0 {
		return false
	}
	return total >= limit
}
